use std::{fmt::Write, path::Path};
fn attr<'a>(tag: &'a str, name: &str) -> &'a str {
    let needle = format!(" {name}=\"");
    tag.split_once(&needle).unwrap_or_else(|| panic!("missing {name}")).1.split('"').next().unwrap()
}
fn number(s: &str) -> f32 {
    let n: f32 = s.parse().expect("SVG coordinate");
    assert!(n.is_finite() && (-1.0..=25.0).contains(&n), "SVG coordinate bounds");
    n
}
fn geometry(svg: &str) -> String {
    assert!(
        svg.contains("viewBox=\"0 0 24 24\"") && svg.contains("stroke-width=\"1.75\"") && svg.contains("fill=\"none\""),
        "SVG family contract"
    );
    let mut out = String::new();
    let mut count = 0;
    for element in svg.split('<').skip(1) {
        if element.starts_with("path ") {
            let mut words = attr(element, "d").split_ascii_whitespace();
            let mut at = (0., 0.);
            let mut start = at;
            while let Some(command) = words.next() {
                let mut next = || number(words.next().expect("SVG path coordinate"));
                let target = match command {
                    "M" => {
                        at = (next(), next());
                        start = at;
                        continue;
                    }
                    "L" => (next(), next()),
                    "H" => (next(), at.1),
                    "V" => (at.0, next()),
                    "Z" => start,
                    _ => panic!("Unsupported SVG path command {command}"),
                };
                write!(out, "Primitive::Line([{:?},{:?},{:?},{:?}]),", at.0, at.1, target.0, target.1).unwrap();
                at = target;
                count += 1;
            }
        } else if element.starts_with("circle ") {
            let (x, y, r) = (number(attr(element, "cx")), number(attr(element, "cy")), number(attr(element, "r")));
            assert!(r > 0. && r <= 12.);
            write!(out, "Primitive::Circle([{:?},{:?},{:?}]),", x, y, r).unwrap();
            count += 1;
        } else {
            assert!(element.starts_with("svg ") || element.starts_with("/svg"), "Unsupported SVG element");
        }
    }
    assert!((1..=64).contains(&count));
    out
}
fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let marker = root.join(".git");
    let git = if marker.is_file() {
        let data = std::fs::read_to_string(&marker).unwrap_or_default();
        root.join(data.trim().strip_prefix("gitdir: ").unwrap_or(".git"))
    } else {
        marker
    };
    println!("cargo:rerun-if-env-changed=KWIL_BUILD_COMMIT");
    let head = git.join("HEAD");
    let common_marker = git.join("commondir");
    println!("cargo:rerun-if-changed={}", head.display());
    println!("cargo:rerun-if-changed={}", common_marker.display());
    let common = std::fs::read_to_string(&common_marker).map(|v| git.join(v.trim())).unwrap_or_else(|_| git.clone());
    let value = std::fs::read_to_string(&head).unwrap_or_default();
    let id = if let Ok(explicit) = std::env::var("KWIL_BUILD_COMMIT") {
        assert!(explicit.len() == 40 && explicit.bytes().all(|b| b.is_ascii_hexdigit()), "invalid KWIL_BUILD_COMMIT");
        explicit
    } else if let Some(reference) = value.trim().strip_prefix("ref: ") {
        let path = common.join(reference);
        let packed = common.join("packed-refs");
        println!("cargo:rerun-if-changed={}", path.display());
        println!("cargo:rerun-if-changed={}", packed.display());
        std::fs::read_to_string(path).unwrap_or_else(|_| {
            std::fs::read_to_string(packed)
                .unwrap_or_default()
                .lines()
                .find_map(|line| {
                    line.split_once(' ').filter(|(_, name)| *name == reference).map(|(id, _)| id.to_owned())
                })
                .unwrap_or_default()
        })
    } else {
        value
    };
    if id.trim().len() == 40 && id.trim().bytes().all(|b| b.is_ascii_hexdigit()) {
        println!("cargo:rustc-env=KWIL_BUILD_COMMIT={}", id.trim());
    }

    // Release builds pass the notices generated by cargo-about (about.toml);
    // other builds point to them.
    println!("cargo:rerun-if-env-changed=KWIL_THIRD_PARTY_NOTICES");
    let notices = match std::env::var_os("KWIL_THIRD_PARTY_NOTICES") {
        Some(path) => {
            println!("cargo:rerun-if-changed={}", Path::new(&path).display());
            std::fs::read_to_string(&path).expect("read KWIL_THIRD_PARTY_NOTICES")
        }
        None => "Third-party notices for the Rust dependencies ship with release builds.".to_owned(),
    };
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("third-party-notices.txt"), notices).unwrap();

    println!("cargo:rerun-if-changed=windows.manifest");
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        let path = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("windows.manifest");
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", path.display());
    }
    let dir = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../assets/icons");
    let mut source = String::from("fn geometry(icon:Icon)-> &'static [Primitive] {match icon {");
    for (name, file) in [
        ("Close", "close"),
        ("Back", "back"),
        ("Forward", "forward"),
        ("Up", "up"),
        ("Down", "down"),
        ("Check", "check"),
        ("Open", "open"),
        ("Save", "save"),
        ("Undo", "undo"),
        ("Redo", "redo"),
        ("GoTo", "goto"),
        ("Settings", "settings"),
        ("Markdown", "markdown"),
        ("Split", "split"),
        ("Text", "text"),
        ("File", "file"),
        ("Sun", "sun"),
        ("Moon", "moon"),
        ("Search", "search"),
        ("Cut", "cut"),
        ("Copy", "copy"),
        ("Paste", "paste"),
        ("Filter", "filter"),
    ] {
        let path = dir.join(format!("{file}.svg"));
        println!("cargo:rerun-if-changed={}", path.display());
        let svg = std::fs::read_to_string(path).unwrap();
        write!(source, "Icon::{name}=> &[{}],", geometry(&svg)).unwrap();
    }
    source.push_str("}}");
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("svg_icons.rs"), source).unwrap();
}
